    def render_confirm_screen(self) -> None:
        import tkinter as tk
        self._clear_content()
        mode = self.state["mode"]
        source = self.state["source"]
        target = self.state["target"]

        # Название режима -- прямо в заголовке (согласовано с пользователем 2026-08-22: "нужен
        # заголовок, который даёт понять, какой режим выбран") -- заменяет прежний отдельный
