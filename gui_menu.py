    def _start_worker(self, mode: str, source, target, log) -> None:
        """Запускает движок в фоновом потоке (§2.1/§2.4 ТЗ). Вызывается ПОСЛЕ render_run_screen()
        -- виджеты уже на экране, дренаж очереди сразу обновляет их. m._run_event_bus/sys.stdout/
        sys.stderr снимаются в _finish_worker() (гарантированная точка -- см. её докстринг), не
        здесь в try/finally -- жизнь воркера растянута на много оборотов Tk mainloop(), обычный
        Python try/finally одного кадра стека тут неприменим."""
        bus = m.RunEventBus()
        self._run_bus = bus
        self._run_orig_stdout = sys.stdout
        self._run_orig_stderr = sys.stderr
        sys.stdout = m._BusTeeStream(bus)
        sys.stderr = m._BusTeeStream(bus)
        m._run_event_bus = bus
        self._run_thread = threading.Thread(
            target=_run_worker_thread, args=(bus, mode, source, target, log), daemon=True)
        self._run_thread.start()
        self._run_drain_job[0] = self.root.after(100, self._drain_bus)

    def _finish_worker(self) -> None:
        """Гарантированная точка снятия bus/stdio (§2.4 ТЗ) -- вызывается ТОЛЬКО из
        _handle_run_event() на событии done/error: воркер к этому моменту уже положил
        последнее, что собирался, в очередь и вот-вот завершится сам -- дальше он больше не
        читает/не пишет ни bus, ни sys.stdout/stderr."""
        self._stop_run_timer()
        m._run_event_bus = None
        if self._run_orig_stdout is not None:
            sys.stdout = self._run_orig_stdout
        if self._run_orig_stderr is not None:
            sys.stderr = self._run_orig_stderr
        self._run_orig_stdout = None
        self._run_orig_stderr = None
        self._run_state = "outcome"

    def _drain_bus(self) -> None:
        """`root.after(100, ...)`-таймер, не колбэк на каждое событие (ось стоимости, §5 ТЗ) --
        вычерпывает ВСЁ накопленное в очереди за один проход, потом планирует себя заново, пока
        экран в состоянии «идёт» (после done/error _finish_worker() уже переключила
        _run_state -- цикл сам останавливается, дополнительный флаг не нужен)."""
        import queue as _queue
        import tkinter as tk
        bus = self._run_bus
        try:
            while True:
                self._handle_run_event(bus.queue.get_nowait())
        except _queue.Empty:
            pass
        if self._run_state == "running":
            try:
                self._run_drain_job[0] = self.root.after(100, self._drain_bus)
            except tk.TclError:
                pass

    def _handle_run_event(self, item) -> None:
        kind = item[0]
        if kind == "status":
            if self._run_status_var is not None:
                self._run_status_var.set(item[1])
        elif kind == "log":
            self._append_run_log_line(item[1])
        elif kind == "done":
            _, report_path, outcome = item
            self._finish_worker()
            self.render_run_outcome(outcome, report_path=report_path)
        elif kind == "error":
            _, text, crashlog_path = item
            self._finish_worker()
            self.render_run_outcome("failed", error_text=text, crashlog_path=crashlog_path)

    def _make_mirror_readonly_copyable(self, mirror) -> None:
        """Панель-зеркало: править нельзя, но выделять/копировать МОЖНО (живой отзыв
        2026-09-01). state="disabled" убил бы и выделение мышью — вместо него блокируем
        правящие нажатия и даём контекстное меню «Копировать» / «Выделить всё»."""
