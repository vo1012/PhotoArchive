    def _pick_source(self) -> None:
        from tkinter import filedialog
        path = filedialog.askdirectory(title=_SOURCE_LABEL, parent=self.root)
        if path:
            self.state["source"] = m._normalize_bare_drive_letter(os.path.normpath(path))
        self.render_paths_screen()

    def _pick_target(self) -> None:
        from tkinter import filedialog
        path = filedialog.askdirectory(title=_TARGET_LABEL[self.state["mode"]], parent=self.root)
        if path:
            self.state["target"] = m._normalize_bare_drive_letter(os.path.normpath(path))
        self.render_paths_screen()

    def _compute_target_info(self) -> dict:
        mode = self.state["mode"]
        if mode == "passport":
            return _describe_passport_target(self.state["target"])
        return _describe_target(mode, self.state["target"], self.state["source"])

    def _paths_valid(self) -> bool:
        mode = self.state["mode"]
        if mode == "view":
            return self.state["source"] is not None
        if mode == "passport":
            return self.state["target"] is not None and self._compute_target_info()["ok"]
        if self.state["source"] is None or self.state["target"] is None:
            return False
        return self._compute_target_info()["ok"]

    def _confirm_paths(self) -> None:
        mode = self.state["mode"]
        if mode in ("dry_run", "build", "passport"):
            info = self._compute_target_info()
            self.state["target"] = info["resolved"]
            self.state["target_comment"] = info
        self.action = "next"
        self.root.quit()

