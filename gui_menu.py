    def _start_keep_alive(self) -> None:
        import tkinter as tk

        def _tick():
            try:
                self._keep_alive_job[0] = self.root.after(200, _tick)
            except tk.TclError:
                pass

        self._keep_alive_job[0] = self.root.after(200, _tick)

    def _stop_keep_alive(self) -> None:
        import tkinter as tk
        if self._keep_alive_job[0] is not None:
            try:
                self.root.after_cancel(self._keep_alive_job[0])
            except tk.TclError:
                pass

