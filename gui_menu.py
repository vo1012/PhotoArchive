def _configure_dpi_awareness() -> None:
    """Один раз за весь запуск, до первого окна -- DPI-awareness процесса нельзя сменить после
    того, как первое окно уже создано. Тот же паттерн флага, что и
    photosort_win._configure_kernel32_console_prototypes() (photosort_win.py:289)."""
    global _dpi_awareness_set
    if _dpi_awareness_set:
        return
    _dpi_awareness_set = True
