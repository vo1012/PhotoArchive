    def _start_run_timer(self, reset: bool = True) -> None:
        """reset=False -- возобновление после паузы: _run_started_at уже сдвинут вперёд на
        длительность паузы в _on_run_pause_toggle(), заново обнулять нельзя."""
        import tkinter as tk

        def _tick():
            elapsed = max(int(time.time() - self._run_started_at), 0)
            try:
                self._run_timer_var.set(f"Прошло: {_fmt_elapsed_clock(elapsed)}")
                self._run_timer_job[0] = self.root.after(1000, _tick)
            except tk.TclError:
                pass

        if reset:
            self._run_started_at = time.time()
        _tick()

    def _stop_run_timer(self) -> None:
        import tkinter as tk
        if self._run_timer_job[0] is not None:
            try:
                self.root.after_cancel(self._run_timer_job[0])
            except tk.TclError:
                pass
            self._run_timer_job[0] = None

    def _on_run_pause_toggle(self) -> None:
        self._run_paused = not self._run_paused
        if self._run_paused:
            self._run_bus.pause_event.set()
            self._run_pause_btn.config(text="Продолжить")
            self._stop_run_timer()  # «Прошло» замирает на время паузы (живой отзыв 2026-09-01)
            self._run_pause_started_at = time.time()
            if self._run_pause_var is not None:
                self._run_pause_var.set("Работа приостановлена")
        else:
            self._run_bus.pause_event.clear()
            self._run_pause_btn.config(text="Пауза")
            if self._run_pause_started_at is not None:
                # сдвигаем точку отсчёта вперёд на длительность паузы -- «Прошло» считает
                # только реальную работу, не время простоя
                self._run_started_at += time.time() - self._run_pause_started_at
                self._run_pause_started_at = None
            if self._run_pause_var is not None:
                self._run_pause_var.set("")
            self._start_run_timer(reset=False)

