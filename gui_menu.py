    def _start_keep_alive(self) -> None:
        import tkinter as tk

        def _tick():
            try:
                self._keep_alive_job[0] = self.root.after(200, _tick)
            except tk.TclError:
                pass

        self._keep_alive_job[0] = self.root.after(200, _tick)

    def _stop_keep_alive(self) -> None:
        import tkinter as tk
        if self._keep_alive_job[0] is not None:
            try:
                self.root.after_cancel(self._keep_alive_job[0])
            except tk.TclError:
                pass

    def _apply_fixed_content_size(self, height_nominal: int, width_nominal=None) -> None:
        """Хвост КАЖДОГО render_*_screen() -- 2026-08-22, по прямой просьбе пользователя
        ("размер окна для каждого шага должен быть фиксирован, не нужно его динамически менять
        в зависимости от выводимого текста") -- ОТМЕНЯЕТ более раннее решение той же сессии
        "сделай высоту адаптивной по экрану" (_fit_content_height()/_fit_paths_screen_height(),
        измерявшие натуральный размер ТЕКУЩЕГО содержимого и подгонявшие под него окно живьём).
        Вместо живого измерения -- заранее посчитанная константа на экран (_MODE_SCREEN_HEIGHT/
        _PATHS_SCREEN_HEIGHT/_RUN_SCREEN_HEIGHT, см. их докстринг -- откуда взялись числа),
        под ХУДШИЙ реалистичный случай контента этого экрана (самый длинный путь, показанный
        динамический комментарий и т.п.) -- один и тот же размер для всех состояний ОДНОГО шага,
        никакого пересчёта на каждый клик/pick. Ширина по-прежнему зафиксирована отдельно
        (_CONTENT_WIDTH) -- эта функция трогает только высоту.

        Безопасно вызывать в ЛЮБОЙ момент, включая изнутри уже запущенного mainloop() (например,
        из _pick_source()/_pick_target() после закрытия диалога выбора папки) -- просто ставит
        уже известную константу, не создаёт/не уничтожает root. Проверка "помещается ли ВООБЩЕ в
        рабочую область экрана" (DPI-cap, может потребовать destroy()+пересборку root с нуля) --
        туда НЕ входит, это отдельная зона ответственности _cap_and_show().

        width_nominal -- своя ширина экрана вместо общей _CONTENT_WIDTH (экран «Выполнение»:
        панель-зеркало 80 моноширинных колонок, см. _RUN_CONTENT_WIDTH). None -> _CONTENT_WIDTH
        (экраны 1-3). _px()-масштабирование то же."""
        self.content.config(
            width=_px(width_nominal if width_nominal is not None else _CONTENT_WIDTH),
            height=_px(height_nominal))
        self.root.update_idletasks()
        _center_window(self.root)

    def _on_close(self) -> None:
        # Крестик/Ctrl-C -- чистый выход из ВСЕГО мастера, одинаково на экранах 1-3 и на
        # состояниях «готово»/«прервано»/«сбой» экрана 4 (работа уже не идёт) -- в отличие от
        # "Назад" (шаг на экран раньше), закрытие окна не пытается вернуться к предыдущему шагу.
        # Экран 4 ПОСРЕДИ реальной обработки (_run_state == "running") -- отдельный протокол
        # (PROMPT_run_screen.md §3.1): подтверждение, жёсткая отмена, sys.exit(0) синхронно,
        # сюда дальше (self.action + root.quit()) не доходит вовсе, см. _on_run_hard_exit().
        if self._run_state == "running":
            self._on_run_hard_exit()
            return
        self.action = "cancel"
        self.root.quit()

    def _on_back(self) -> None:
        self.action = "back"
        self.root.quit()

