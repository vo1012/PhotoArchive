def probe_display_available() -> bool:
    """Раунд 114 (замечание 2): узкая проверка "может ли GUI вообще открыться" (нет дисплея,
    tkinter не установлен и т.п.), ОТДЕЛЬНАЯ от самого run_bare_launch() -- вызывающая сторона
    (photosort_win._main()) должна ловить исключением только этот шаг, не всю мастер-сессию,
    иначе реальный сбой посреди сборки архива неотличим от "GUI недоступен" и теряется без
    crash.log (см. PROMPT_review.md, раунд 114). Создаёт и сразу уничтожает пробный tk.Tk().
    Раунд 115 (замечание): _configure_dpi_awareness() вызывается ПЕРЕД tk.Tk() -- это первое
    окно процесса на GUI-пути, а DPI-awareness нельзя сменить после того, как окно уже создано.
    Раунд 115 (придирка, закрыта раунд 116-раунд ответа): probe.destroy() -- отдельный try/except
    от tk.Tk() -- сбой ИМЕННО очистки (окно успело открыться, значит GUI реально доступен) не
    должен ложно классифицироваться как "GUI недоступен" наравне со сбоем самого tk.Tk()."""
    _configure_dpi_awareness()
    try:
        import tkinter as tk
        probe = tk.Tk()
    except Exception:
        return False
    try:
        probe.destroy()
    except Exception:
        pass
    return True


def _configure_dpi_awareness() -> None:
    """Один раз за весь запуск, до первого окна -- DPI-awareness процесса нельзя сменить после
    того, как первое окно уже создано. Тот же паттерн флага, что и
    photosort_win._configure_kernel32_console_prototypes() (photosort_win.py:289)."""
    global _dpi_awareness_set
    if _dpi_awareness_set:
        return
    _dpi_awareness_set = True
    if os.name != "nt":
        return
    try:
        import ctypes
        ctypes.windll.shcore.SetProcessDpiAwareness(1)  # PROCESS_SYSTEM_DPI_AWARE
    except Exception:
        pass


def _compute_dpi_scale(root) -> None:
    """Реальный клик-тест на HTPC (2026-08-21, SESSION-HANDOFF.txt) нашёл: Tk сам определяет
    DPI монитора и масштабирует ШРИФТЫ (заданные в pt) пропорционально ей (tk scaling =
    DPI/72) -- а все пиксельные размеры этого модуля (_CONTENT_WIDTH/высота шапки/padx/pady)
    заданы голыми, НЕ масштабируемыми числами. На 4K-мониторе (реальная
    машина, tk scaling ~4.0) это расходится: шрифт "Segoe UI 18" рендерится ~102px вместо
    расчётных ~24px, текст выходит за пределы своих же контейнеров (шапка/карточки режима) --
    на экране 1 из 4 карточек влезала одна, с обрезанным и наползающим друг на друга текстом.

    Первая версия фикса (2026-08-21) замораживала `tk scaling=1.0` -- решала переполнение, но
    ценой рассинхрона с ОС: наш текст переставал расти вместе с реальным DPI, а системные
    элементы (например, диалог `filedialog.askdirectory()` -- отдельное Explorer-окно,
    Tk-масштаб на него не действует) оставались в родном масштабе Windows, из-за чего шрифт
    мастера выглядел заметно мельче шрифта диалога выбора папки на одном и том же экране --
    замечено пользователем на реальном железе тем же заходом. Правильный фикс -- не мешать
    Tk масштабировать шрифты (как он и делает по умолчанию), а вместо этого масштабировать
    ВСЕ пиксельные константы макета (`_px()` ниже) ТЕМ ЖЕ коэффициентом, каким Tk уже
    масштабирует точки шрифта -- тогда контейнеры растут вместе с текстом.

    Промежуточная версия этого фикса ошибочно брала `winfo_fpixels("1i")/96` (DPI относительно
    96 -- конвенция Windows "логического пикселя") -- НЕ совпадает с тем, что реально использует
    Tk для шрифтов (`tk scaling` = DPI/72, точка -- это 1/72 дюйма, не 1/96): на реальном 4K-
    экране разница 96 vs 72 в знаменателе давала расхождение ×1.33 между тем, насколько выросли
    шрифты, и тем, насколько выросли контейнеры -- макет, изначально подобранный (и провалидиро-
    ванный первой версией фикса) под `tk scaling=1.0`, при таком масштабе снова начинал
    переполняться (подпись "Enter — ..." под карточками уезжала за пределы контент-блока).
    Правильно -- взять РЕАЛЬНЫЙ `tk scaling` Tk напрямую, не пересчитывать его самостоятельно
    через другую единицу: тогда при `tk scaling==1.0` (as-is on non-HiDPI) `_px(n)==n`, в точности
    те же пропорции, что уже провалидированы кликом на этой машине."""
    global _dpi_scale
    _dpi_scale = root.tk.call("tk", "scaling")


def _px(n: int) -> int:
    """Масштабирует пиксельную константу макета под реальный DPI монитора (см.
    _compute_dpi_scale()) -- тем же коэффициентом, каким Tk уже масштабирует шрифты (заданные
    в pt), чтобы контейнеры росли вместе с текстом, который в них должен поместиться."""
    return round(n * _dpi_scale)


def _get_work_area(root) -> tuple:
    """Реальный клик-тест на HTPC (2026-08-21, SESSION-HANDOFF.txt) нашёл: на этом мониторе
    честное пропорциональное масштабирование (см. _compute_dpi_scale()) даёт окну требуемую
    высоту 2472px при экране 2160px -- окно физически не помещается, кнопки навигации внизу
    обрезаются. `winfo_screenheight()` -- это высота ВСЕГО экрана, не рабочей области (не
    учитывает панель задач) -- используем `SPI_GETWORKAREA` (реальные физические пиксели,
    т.к. вызывается уже после SetProcessDpiAwareness) как более точный и чуть более
    консервативный предел. Не-Windows/сбой API -- откат на winfo_screenheight() с запасом."""
    if os.name == "nt":
        try:
            import ctypes

            class _RECT(ctypes.Structure):
                _fields_ = [("left", ctypes.c_long), ("top", ctypes.c_long),
                            ("right", ctypes.c_long), ("bottom", ctypes.c_long)]

            SPI_GETWORKAREA = 0x0030
            rect = _RECT()
            if ctypes.windll.user32.SystemParametersInfoW(SPI_GETWORKAREA, 0,
                                                            ctypes.byref(rect), 0):
                return rect.right - rect.left, rect.bottom - rect.top
        except Exception:
            pass
    return root.winfo_screenwidth(), max(root.winfo_screenheight() - 80, 1)


def _chrome_margin(root) -> int:
    """Реальная высота заголовка+рамки окна, которую Windows (DWM) добавляет ПОВЕРХ
    winfo_reqwidth/height() (Tk меряет только клиентскую область, не окно целиком) -- нужна и
    _cap_dpi_scale_to_fit(), и _center_window() ниже, чтобы не отрезать/не сдвигать окно под
    панель задач. Найдено 2026-08-22 клик-тестом в ДВА захода: (1) голая константа 60 -- это 60
    ФИЗИЧЕСКИХ пикселей независимо от DPI, а реальная рамка+заголовок на этом мониторе съедают
    ~103px; (2) `_px(40)` тоже оказалась неверна -- `_px()` масштабирует ПО `_dpi_scale`, а её же
    может УМЕНЬШИТЬ вызывающая функция (`_cap_dpi_scale_to_fit()`) -- рамку рисует DWM по
    РЕАЛЬНОМУ системному масштабу монитора, который от внутренней коррекции `_dpi_scale` не
    меняется (подтверждено повторным замером -- рамка осталась теми же ~103px и после того, как
    `_dpi_scale` был уже уменьшен). Правильная единица -- DPI/96 (тот же расчёт, что
    _compute_dpi_scale() в своё время ОТВЕРГЛА для масштабирования КОНТЕНТА, т.к. не совпадает с
    tk-шрифтовым `tk scaling` -- но здесь нужен ровно он, окно рисует не Tk).

    Константа откалибрована под то самое измерение (2026-08-22, Раунд 121 ревью, замечание --
    прежняя константа 50 была подобрана на глаз, не под реально измеренные ~103px: на тестовой
    машине DPI≈288 -> os_scale=3.0 -> round(50*3.0)=150, разошлось с измерением на ~46%).
    34 * 3.0 = 102 -- ближайшее целое к измеренным ~103px на том самом os_scale."""
    try:
        os_scale = max(root.winfo_fpixels("1i") / 96, 1.0)
    except Exception:
        os_scale = 1.0
    return round(34 * os_scale)


def _cap_dpi_scale_to_fit(root, required_width: int, required_height: int) -> bool:
    """Если честный DPI-масштаб (_compute_dpi_scale()) даёт окну размер больше рабочей области
    экрана -- пропорционально уменьшает `_dpi_scale`, чтобы окно гарантированно поместилось (с
    запасом на рамку/заголовок окна, см. _chrome_margin()). Никогда не уменьшает масштаб НИЖЕ
    1.0 -- это уже провалидированный кликом минимум (макет, как он задуман без какого-либо DPI-
    масштабирования вообще), дальше сжимать некуда, лучше слегка не поместиться, чем стать
    нечитаемо мелким. Возвращает True, если масштаб пришлось скорректировать (вызывающая сторона
    должна пересобрать окно с ним)."""
    global _dpi_scale
    work_w, work_h = _get_work_area(root)
    chrome_margin = _chrome_margin(root)
    available_w = max(work_w - chrome_margin, 1)
    available_h = max(work_h - chrome_margin, 1)
    if required_width <= available_w and required_height <= available_h:
        return False
    factor = min(available_w / required_width, available_h / required_height)
    new_scale = max(_dpi_scale * factor, 1.0)
    if new_scale >= _dpi_scale:
        return False
    _dpi_scale = new_scale
    return True


def _center_window(root) -> None:
    """Центрирует относительно РАБОЧЕЙ области (см. _get_work_area()), не всего экрана --
    найдено 2026-08-22 клик-тестом новой раскладки экрана 1: `winfo_screenheight()` включает
    панель задач, поэтому даже окно, которое `_cap_dpi_scale_to_fit()` уже признал помещающимся
    В РАБОЧУЮ область по высоте, при центрировании по ПОЛНОЙ высоте экрана всё равно съезжало
    вниз настолько, что нижний край (строка навигации) прятался под панелью задач.

    Второй заход тем же днём: даже после переключения на рабочую область окно ВСЁ РАВНО слегка
    вылезало снизу -- `height` здесь (`winfo_reqheight()`) это высота только КЛИЕНТСКОЙ области,
    без рамки/заголовка (см. _chrome_margin()), а `geometry("+x+y")` позиционирует ВЕРХНИЙ
    ЛЕВЫЙ УГОЛ ОКНА ЦЕЛИКОМ (с рамкой). Заголовок сидит СВЕРХУ и несимметричен (снизу рамка
    почти нулевая) -- центрирование по одной лишь клиентской высоте не резервирует под него
    место вообще, окно физически суммарно выше, чем `height`, и съезжает вниз ровно на высоту
    заголовка. Вычитаем `_chrome_margin(root)` из доступной высоты ДО деления пополам -- тогда
    результирующий отступ сверху `y` уже включает место под заголовок, а не выделяется поверх
    вычисленного центра."""
    root.update_idletasks()
    width = root.winfo_reqwidth()
    height = root.winfo_reqheight()
    work_w, work_h = _get_work_area(root)
    chrome = _chrome_margin(root)
    x = max((work_w - width) // 2, 0)
    y = max((work_h - height - chrome) // 2, 0)
    root.geometry(f"+{x}+{y}")


