    def render_mode_screen(self) -> None:
        import tkinter as tk
        self._clear_content()
        self.step_var.set("Шаг 1 из 3: Выбор режима (Что необходимо сделать?)")
        # Кнопка режима и её описание -- одна строка ОБЩЕЙ grid-таблицы, не два независимых
        # pack-столбца, как в предыдущей версии (2026-08-22, находка пользователя: "комментарии
        # сдвинуты по вертикали относительно кнопок" -- при двух независимых столбцах высота i-й
        # кнопки не была синхронизирована с высотой i-го блока описания, разница накапливалась
        # вниз по списку). Обе ячейки строки -- sticky="nw", grid() сам делает высоту строки
        # максимумом из двух ячеек и держит их общий верх -- дрейф структурно невозможен.
        # Никакого дублирования названия режима в описании (согласовано с пользователем) --
        # оно и так стоит на кнопке в той же строке, повторять незачем.
        grid = tk.Frame(self.content, bg=_BG)
        grid.pack(fill="both", expand=True)
        grid.columnconfigure(0, minsize=_px(_MODE_BTN_COL_WIDTH))
        grid.columnconfigure(1, weight=1)
        comment_wrap = _px(_MODE_COMMENT_WIDTH)

        # "Выход из программы" -- полноценный пункт списка (2026-08-22, по прямой просьбе
        # пользователя), заменяет прежнюю отдельную кнопку "Выход" в нижней панели навигации --
        # команда та же (self._on_close()), просто теперь это строка списка, а не кнопка внизу.
        rows = [(m._BARE_LAUNCH_MODE_LABELS[mode], _MODE_DESCRIPTIONS[mode],
                 lambda mm=mode: self._choose_mode(mm)) for mode in _MODE_ORDER]
        rows.append((_EXIT_LABEL, _EXIT_DESCRIPTION, self._on_close))
        for i, (label, desc, command) in enumerate(rows):
            row_pad = (0, 0) if i == len(rows) - 1 else (0, _px(8))
            tk.Button(grid, text=label, font=("Segoe UI", 10), anchor="w",
                       padx=_px(12), pady=_px(8), command=command).grid(
                row=i, column=0, sticky="ew", pady=row_pad)
            tk.Label(grid, text=desc, bg=_BG, fg=_MUTED, font=("Segoe UI", 9), anchor="nw",
                      justify="left", wraplength=comment_wrap).grid(
                row=i, column=1, sticky="nw", padx=(_px(16), 0), pady=row_pad)

        # Ни "Enter -> Посмотреть" по умолчанию, ни фокуса ни на одном пункте, ни кнопки "Далее"
        # на этом экране больше нет (2026-08-22, по прямой просьбе пользователя) -- выбор режима
        # начинается только явным кликом по пункту списка, без скрытого клавиатурного пути.
        # unbind(), не просто "не забиндить заново" -- если сюда вернулись с экрана 2/3 через
        # "Назад", root ещё помнит ИХ обработчик Return (например, _confirm_paths()) -- без
