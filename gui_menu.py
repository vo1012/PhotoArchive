    def _configure_nav(self, back_enabled: bool, next_label, next_enabled: bool,
                        next_command, show_cancel: bool = True) -> None:
        import tkinter as tk
        # Каждая из трёх кнопок нижней панели скрывается целиком (pack_forget), не просто
        # дизейблится, когда неактуальна на текущем экране -- показывать серую кнопку без
        # действия было бы лишним визуальным шумом (экран 1 вообще не показывает ни одной --
        # show_cancel=False, next_label=None -- "Выход" там теперь пункт списка режимов, а
        # "Назад"/"Далее" на первом шаге были бы кнопками в никуда).
        if show_cancel:
            self.cancel_btn.pack(side="left")
        else:
            self.cancel_btn.pack_forget()
        # before=cancel_btn держит порядок слева направо (Назад, Выход) даже после повторного
        # pack() на следующем экране -- back_enabled==True никогда не сочетается с
        # show_cancel=False на практике (экран 1 -- единственный с show_cancel=False -- поэтому
        # cancel_btn там уже гарантированно упакован раньше, before= не сломается).
        if back_enabled:
            self.back_btn.pack(side="left", padx=(0, _px(10)), before=self.cancel_btn)
        else:
            self.back_btn.pack_forget()
        if next_label is None:
            self.next_btn.pack_forget()
        else:
            self.next_btn.config(text=next_label, command=next_command,
                                   state=(tk.NORMAL if next_enabled else tk.DISABLED))
            self.next_btn.pack(side="right")

