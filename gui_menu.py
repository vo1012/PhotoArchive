        # "до"/"после" выбора имели РАЗНЫЕ padx/pady и только "до" использовала wraplength,
        # из-за чего визуально сильно отличались по размеру даже без слова-разницы выше.
        #
        # Раунд правок 2026-08-22 (продолжение) -- ТА ЖЕ находка пользователя оказалась шире,
        # чем один только padx/pady/wraplength: sticky="nw" НЕ растягивает кнопку до ширины
        # колонки (grid.columnconfigure(0, minsize=_PATH_BTN_COL_WIDTH) в render_paths_screen()
        # задаёт только МИНИМУМ колонки, не размер самой кнопки) -- кнопка сама по себе
        # схлопывается до natural-размера СВОЕГО текста, поэтому "Выбрать источник фотографий"
