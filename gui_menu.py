    def render_paths_screen(self) -> None:
        import tkinter as tk
        self._clear_content()
        mode = self.state["mode"]
        # Заголовок называет режим явно (2026-08-22, живая находка пользователя -- "меню
        # второго уровня не даёт информации о том, какой режим сейчас работает"; заголовок --
        # одна строка, тот же формат, что уже применяется на экране 3, для единообразия).
        self.step_var.set(f"Шаг 2 из 3: Выбор путей (Режим: "
                            f"{m._BARE_LAUNCH_MODE_LABELS[mode]})")

        needs_source = mode in ("view", "dry_run", "build")
        needs_target = mode in ("dry_run", "build", "passport")

        # 2026-08-22, редизайн по живой обратной связи пользователя -- три отдельных находки,
        # реализованы одним заходом, т.к. меняют одну и ту же раскладку:
        # (1) "что выбираем" -- в тексте самой кнопки (_render_path_row() ниже), не в отдельном
        #     заголовке над блоком (убирает дублирование "Выбор путей"/"Откуда взять
        #     фотографии" -- заголовок экрана и подпись блока раньше говорили о одном и том же
        #     двумя разными словами).
        # (2) "зачем"/что будет сделано -- статичный комментарий (_SOURCE_STATIC_COMMENT/
        #     _TARGET_STATIC_COMMENT) СПРАВА от кнопки, для КАЖДОГО пути, не только для target.
        # (3) выбранный путь -- не под кнопкой в узкой колонке (было тесно, длинные пути
        #     переносились на много строк в 300px), а отдельной строкой НА ВСЮ ширину content.
        # Динамический статус-комментарий (архив уже есть/корень диска/и т.п., ТОЛЬКО для
        # target, только после выбора) -- отдельным блоком ПОД обоими путями, тоже на всю
        # ширину, а не в колонке рядом с конкретной кнопкой -- он не про "что выбираем", а про
        # состояние уже сделанного последнего выбора (то же обоснование, что и для (3)).
        grid = tk.Frame(self.content, bg=_BG)
        grid.pack(fill="x")
        grid.columnconfigure(0, minsize=_px(_PATH_BTN_COL_WIDTH))
        grid.columnconfigure(1, weight=1)
        row = 0
        if needs_source:
            row = self._render_path_row(grid, row, _SOURCE_BUTTON_TEXT,
                                          _SOURCE_STATIC_COMMENT, self.state["source"],
                                          self._pick_source)
        if needs_target:
            row = self._render_path_row(grid, row, _TARGET_BUTTON_TEXT[mode],
                                          _TARGET_STATIC_COMMENT[mode], self.state["target"],
                                          self._pick_target)

        if needs_target:
            # ФИКСИРОВАННАЯ высота этого блока -- ВСЕГДА резервируется, даже пока target не
            # выбран (2026-08-22, по прямой просьбе пользователя, "не нужно динамически менять
            # расположение уже выведенных элементов") -- раньше блок вообще не существовал до
            # выбора target, из-за чего его появление сдвигало нижнюю панель навигации вниз.
            # pack_propagate(False) держит высоту постоянной независимо от того, есть ли внутри
            # реальный _render_comment_box() или пусто.
            dynamic_wrap = tk.Frame(self.content, bg=_BG, height=_px(_PATHS_DYNAMIC_COMMENT_HEIGHT))
            dynamic_wrap.pack_propagate(False)
            dynamic_wrap.pack(fill="x", pady=(_px(6), 0))
            if self.state["target"] is not None:
                info = self._compute_target_info()
                _render_comment_box(dynamic_wrap, info["message"], info["tone"])

